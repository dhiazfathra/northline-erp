// usage: node tools/parity/index.mjs — writes docs/parity/README.md, an index of every scenario README under
// docs/parity/<module>/<form>/ with its verdict (read from the README's "**Verdict:**" line).
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../../docs/parity/', import.meta.url).pathname;
const rows = [];
for (const mod of readdirSync(root).sort()) {
  if (!statSync(join(root, mod)).isDirectory()) continue;
  for (const form of readdirSync(join(root, mod)).sort()) {
    const file = join(root, mod, form, 'README.md');
    let text; try { text = readFileSync(file, 'utf8') } catch { continue }
    const title = /^# (.+)$/m.exec(text)?.[1] ?? form;
    const verdict = /^\*\*Verdict:\*\* (.+)$/m.exec(text)?.[1] ?? 'unknown';
    const module = /^Module: ([^.]+)\./m.exec(text)?.[1] ?? mod;
    const date = /^Date: (\d{4}-\d{2}-\d{2})/m.exec(text)?.[1] ?? '';
    rows.push(`| ${module} | [${title}](${mod}/${form}/README.md) | ${verdict} | ${date} |`);
  }
}
if (!rows.length) throw new Error('no scenario READMEs found');
writeFileSync(join(root, 'README.md'), `# Screen parity evidence (P4)

Generated by \`node tools/parity/index.mjs\` from the per-scenario READMEs; do not edit by hand. Scenarios run with
\`tools/parity/run.mjs <scenario>\` (see docs/goals/full-parity-v2.md §P4 and §Evidence). Divergences: ADR-0041 (batch 1), ADR-0042 (batch 2), ADR-0043 (batch 3), ADR-0044 (batch 4).

| Module | Form | Verdict | Date |
|---|---|---|---|
${rows.join('\n')}
`);
console.log(`indexed ${rows.length} scenarios`);
