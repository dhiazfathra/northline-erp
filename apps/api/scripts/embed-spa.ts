// Writes src/spa.generated.ts importing every file of apps/web/dist with `type: 'file'`,
// so `bun build --compile` packs the SPA into the binary.
import { Glob } from 'bun'
const dist = new URL('../../web/dist/', import.meta.url).pathname
const files = [...new Glob('**/*').scanSync(dist)].sort()
const lines = files.map((f, i) => `import a${i} from '../../web/dist/${f}' with { type: 'file' }`)
await Bun.write(new URL('../src/spa.generated.ts', import.meta.url).pathname,
  `// generated by scripts/embed-spa.ts\n${lines.join('\n')}\nexport const assets: Record<string, string> = {\n${files.map((f, i) => `  ${JSON.stringify(f)}: a${i},`).join('\n')}\n}\n`)
console.log(`embedded ${files.length} files`)
